function tD(k) {
  const l = window.BI10_LANG || 'vi';
  return (DECISION_I18N[l] && DECISION_I18N[l][k]) || (DECISION_I18N['en'] && DECISION_I18N['en'][k]) || k;
}

function applyDecisionStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if (k) el.innerHTML = tD(k);
  });
}

